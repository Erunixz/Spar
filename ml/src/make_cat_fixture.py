"""Parity fixture for the app's CAT engine: full simulated placements from the
Python mirror, which the TypeScript test replays step by step.

Usage (from ml/): .venv/Scripts/python -m src.make_cat_fixture
"""

from __future__ import annotations

import json
import random

from src import cat

OUT = cat.REPO / "apps" / "web" / "src" / "engine" / "__fixtures__" / "cat-parity.json"


def simulate(items, patterns, true_theta: dict[str, float], seed: int) -> list[dict]:
    rng = random.Random(seed)
    bank = {i.id: i for i in items}
    responses: list[tuple[str, bool]] = []
    steps = []
    while True:
        general, per = cat.estimate_all(bank, patterns, responses)
        choice = cat.next_item(items, patterns, responses, estimates=(general, per))
        stop = cat.stop_reason(responses, per, choice is not None)
        step = {
            "general": list(general),
            "patterns": {p: list(v) for p, v in per.items()},
            "stop": stop,
        }
        if stop is None:
            item, pattern = choice
            # Multi-pattern items: answer with the mean ability of their patterns.
            theta = sum(true_theta[p] for p in item.patterns) / len(item.patterns)
            correct = rng.random() < cat.icc(theta, item.a, item.b)
            step |= {"itemId": item.id, "pattern": pattern, "correct": correct}
            responses.append((item.id, correct))
        steps.append(step)
        if stop:
            return steps


def main() -> None:
    items, patterns = cat.load_bank()
    rng = random.Random(42)
    examinees = []
    for k, general in enumerate((-0.8, 0.2, 1.1)):
        true_theta = {p: general + rng.gauss(0, 0.8) for p in patterns}
        examinees.append({"trueTheta": true_theta, "steps": simulate(items, patterns, true_theta, seed=k)})
    fixture = {
        "note": "Generated by ml/src/make_cat_fixture.py from the Python CAT mirror. Do not edit by hand.",
        "patterns": patterns,
        "items": [{"id": i.id, "patterns": list(i.patterns), "a": i.a, "b": i.b} for i in items],
        "examinees": examinees,
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(fixture, indent=1) + "\n", encoding="utf-8")
    print("wrote", OUT.name, "| items asked:", [sum("itemId" in s for s in e["steps"]) for e in examinees],
          "| stops:", [e["steps"][-1]["stop"] for e in examinees])


if __name__ == "__main__":
    main()
